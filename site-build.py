#!/usr/bin/env python3
"""Stamp cache-busting versions after editing the site.

    python3 site-build.py

- index.html loads assets/app.js, explore.js and analytics.js with ?v=<hash of each file>
- vedic-math/index.html gets an import map that pins every module under /vedic-math/js/
  (skills/ included) to ?v=<hash of that file>, so a visitor never runs a new app.js
  against old imports. The entry script, its stylesheets, explore.js and analytics.js
  are stamped the same way. The map sits between the "site-build: import map" markers
  and is rewritten on every run. The /design-system/ stylesheets come from the
  sbmadhav/design-system repo, so their ?v= stamps are left as they are.
- sw.js gets a new VERSION (hash of every file the site serves from the cache: pages,
  scripts, Vedic Math modules, fonts, icons) so any change rotates the service worker cache.
  The /design-system/ files it precaches are not in this repo, so they are not hashed; the
  worker refreshes them in the background on every visit (stale-while-revalidate).

Running it twice changes nothing the second time.
"""
import hashlib, json, pathlib, posixpath, re

root = pathlib.Path(__file__).resolve().parent
h = lambda b: hashlib.sha256(b).hexdigest()[:10]
fhash = lambda p: h((root / p).read_bytes())

def write(path, text):
    f = root / path
    if f.read_text() != text:
        f.write_text(text)

# ---------- home page ----------
SCRIPTS = ["assets/app.js", "assets/explore.js", "assets/analytics.js"]
versions = {p: fhash(p) for p in SCRIPTS}

def stamp(text):
    for p, v in versions.items():
        text = re.sub(r"(?<![\w/.-])" + re.escape(p) + r"\?v=[\w_]+", f"{p}?v={v}", text)
    return text

html = stamp((root / "index.html").read_text())
write("index.html", html)

# ---------- Vedic Math: import map + stamped entry, styles and shared scripts ----------
VM = "vedic-math"
vm_js = sorted(p.relative_to(root).as_posix() for p in (root / VM / "js").rglob("*.js"))
vm_versions = {"/" + p: fhash(p) for p in vm_js}

# Every static import must be a relative or absolute path inside /vedic-math/js/, or a full URL
# (CDN). A bare specifier would fail without the map, and a path outside the folder would not be pinned.
import_re = re.compile(r"""(?:^|[;\n}])\s*(?:import|export)\b[^'"`;]*?\bfrom\s*['"]([^'"]+)['"]|(?:^|[;\n}])\s*import\s*['"]([^'"]+)['"]""")
for p in vm_js:
    src = (root / p).read_text()
    for m in import_re.finditer(src):
        spec = m.group(1) or m.group(2)
        if re.match(r"https?://", spec):
            continue
        if not spec.startswith(("./", "../", "/")):
            raise SystemExit(f"{p}: bare import '{spec}' is not covered by the import map")
        resolved = posixpath.normpath(spec if spec.startswith("/") else posixpath.join(posixpath.dirname("/" + p), spec))
        if resolved not in vm_versions:
            raise SystemExit(f"{p}: import '{spec}' resolves to {resolved}, outside the versioned /vedic-math/js/ modules")

imports = {u: f"{u}?v={v}" for u, v in vm_versions.items()}
MAP_START, MAP_END = "<!-- site-build: import map (generated by site-build.py, do not edit) -->", "<!-- /site-build: import map -->"
map_block = MAP_START + '\n<script type="importmap">\n' + json.dumps({"imports": imports}, indent=1) + "\n</script>\n" + MAP_END + "\n"

vm_html = (root / VM / "index.html").read_text()
vm_html = re.sub(re.escape(MAP_START) + r".*?" + re.escape(MAP_END) + r"\n?", "", vm_html, flags=re.S)
entry = re.search(r'<script type="module" src="/vedic-math/js/app\.js(?:\?v=[\w_]+)?"></script>', vm_html)
if not entry:
    raise SystemExit("vedic-math/index.html: module entry script not found")
vm_html = vm_html[:entry.start()] + map_block + vm_html[entry.start():]
assert vm_html.count('type="importmap"') == 1

page_assets = {
    "/vedic-math/js/app.js": vm_versions["/vedic-math/js/app.js"],
    "/vedic-math/math.css": fhash("vedic-math/math.css"),
    **{"/" + p: v for p, v in versions.items() if p != "assets/app.js"},
}
for url, v in page_assets.items():
    vm_html, n = re.subn(r'((?:src|href)=")' + re.escape(url) + r'(?:\?v=[\w_]+)?"', rf'\g<1>{url}?v={v}"', vm_html)
    if not n:
        raise SystemExit(f"vedic-math/index.html: no reference to {url}")
write(f"{VM}/index.html", vm_html)

# ---------- service worker ----------
sw = stamp((root / "sw.js").read_text())
precache = re.search(r"const PRECACHE = \[(.*?)\];", sw, re.S).group(1)
cached = set()
for entry_path in re.findall(r"'([^']+)'", precache):
    p = entry_path.split("?")[0].lstrip("./")
    p = p + "index.html" if p == "" or p.endswith("/") else p
    if (root / p).is_file():
        cached.add(p)
cached |= {"index.html", "vedic-math/index.html", "vedic-math/math.css", *SCRIPTS, *vm_js}
cached |= {p.relative_to(root).as_posix() for p in (root / "assets" / "fonts").glob("*") if p.is_file()}
digest = hashlib.sha256()
for p in sorted(cached):
    digest.update(p.encode() + b"\0" + (root / p).read_bytes() + b"\0")
version = digest.hexdigest()[:10]
sw = re.sub(r"const VERSION = '[^']*';", f"const VERSION = '{version}';", sw)
write("sw.js", sw)

print(", ".join(f"{p} v={v}" for p, v in versions.items())
      + f", {len(imports)} Vedic Math modules pinned, service worker VERSION={version} ({len(cached)} files)")
